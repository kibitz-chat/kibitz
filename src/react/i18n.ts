const TABLES: Record<WLang, Record<string, string>> = { en: {}, he: HE, ar: AR, ru: RU, fr: FR, es: ES, de: DE, it: IT, pt: PT, zh: ZH, hi: HI, ja: JA, ko: KO, nl: NL, pl: PL, uk: UK, tr: TR }

/** Translate kibitz-chrome English text to the current call language. English is the key; an unknown key
 *  falls through to the English. `vars` interpolates `{name}`-style tokens after the lookup. */
export const wt = (en: string, vars?: Record<string, string | number>): string => {
  let s = TABLES[wlang()]?.[en] ?? en
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]))
  return s
}
