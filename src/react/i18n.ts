// Static, table-driven localization for the kibitz call UI's OWN chrome — the status words, state hints,
// summon + credit affordances, and tile activity labels that the widget / CallSurface render themselves.
// The AGENT's own button + capability labels are NOT here: the agent already ships them localized in its
// `agent-actions@1` manifest (agent/actions.mjs buildManifest(lang)), and the UI uses those directly. This
// table is only for the vocabulary kibitz owns and no manifest describes.
//
// Mirrors witz.chat's static-table approach (witz/public/i18n.js): nothing translates online, EN + HE only
// for now, and the English text IS the key — so adding a language is one column, and adding a string needs
// no key ceremony. `{name}` / `{n}` tokens interpolate AFTER lookup.
//
// One call = one language. It's resolved from (in order): the language the agent advertises in its manifest
// (preferred — it travels with the agent to any surface / late-joiner), then the `l=` param the gift flow
// puts in the room-link fragment (`…/#<room>?…&l=he`), then English.
import { splitRoomHash } from '../core/joinGateLink'

export type WLang = 'en' | 'he' | 'ar' | 'ru' | 'fr' | 'es' | 'de' | 'it' | 'pt' | 'zh' | 'hi' | 'ja' | 'ko' | 'nl' | 'pl' | 'uk' | 'tr'
const SUPPORTED = new Set<string>(['en', 'he', 'ar', 'ru', 'fr', 'es', 'de', 'it', 'pt', 'zh', 'hi', 'ja', 'ko', 'nl', 'pl', 'uk', 'tr'])
const norm = (v: string | null | undefined): WLang | null => {
  const s = (v || '').trim().toLowerCase().slice(0, 2)
  return SUPPORTED.has(s) ? (s as WLang) : null
}

// Read the URL language once at load (safe when there's no DOM — tests / SSR fall back to English).
let urlLang: WLang = 'en'
try {
  const frag = splitRoomHash(location.hash).params.get('l')
  const qs = new URLSearchParams(location.search).get('l')
  urlLang = norm(frag) ?? norm(qs) ?? 'en'
} catch {
  /* no DOM → English */
}

// The agent's advertised language wins over the URL once its manifest is parsed (set from liveAgentMenus).
let agentLang: WLang | null = null
export const noteAgentLang = (v: string | null | undefined): void => {
  const n = norm(v)
  if (n) agentLang = n
}
/** The current call language (agent-advertised beats URL beats English). */
export const wlang = (): WLang => agentLang ?? urlLang
const RTL = new Set<WLang>(['he', 'ar'])
export const isRtl = (): boolean => RTL.has(wlang())

