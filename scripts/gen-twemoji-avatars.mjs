// One-time generator: fetch the Twemoji SVG for each avatar emoji and vendor them into
// src/widget/twemojiAvatars.ts as an emoji→SVG-string map. Bundling (vs a runtime CDN) keeps the widget
// self-contained: avatars render IDENTICALLY on every device, work offline (LAN hub), and leak nothing to
// a CDN. Re-run if the AVATARS set changes: `node scripts/gen-twemoji-avatars.mjs`.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

// Keep in sync with AVATARS in src/widget/Widget.tsx, plus the 🙂 default.
const EMOJI = ['😀', '😎', '🤓', '🥳', '😺', '🦊', '🐼', '🐵', '🦁', '🐸', '🐯', '🐨', '🤖', '👽', '🦄', '🐲', '🔥', '⭐', '🙂']
const VER = '15.1.0' // jdecked/twemoji (the maintained fork)

// Twemoji filename = the emoji's code points in lowercase hex, joined by '-', with the FE0F
// variation selector dropped (its default for single-glyph emoji). Try that; fall back to keeping FE0F.
const cps = (s) => [...s].map((c) => c.codePointAt(0).toString(16))
const nameNoFe0f = (s) => cps(s).filter((h) => h !== 'fe0f').join('-')
const nameWithFe0f = (s) => cps(s).join('-')

const fetchSvg = async (file) => {
  const r = await fetch(`https://cdn.jsdelivr.net/gh/jdecked/twemoji@${VER}/assets/svg/${file}.svg`)
  return r.ok ? (await r.text()).trim() : null
}

const map = {}
for (const e of EMOJI) {
  let svg = await fetchSvg(nameNoFe0f(e))
  if (!svg) svg = await fetchSvg(nameWithFe0f(e))
  if (!svg) {
    console.error(`✗ no Twemoji SVG for ${e} (${nameNoFe0f(e)})`)
    process.exit(1)
  }
  // Strip the XML width/height so CSS (width:1em) controls the size; keep the viewBox.
  map[e] = svg.replace(/\s(width|height)="[^"]*"/g, '')
  console.error(`✓ ${e} → ${nameNoFe0f(e)}.svg (${svg.length}b)`)
}

const out = `// AUTO-GENERATED by scripts/gen-twemoji-avatars.mjs — do not edit by hand.
// Twemoji (jdecked/twemoji ${VER}, CC-BY 4.0) SVGs for the avatar emoji set, vendored so avatars render
// identically on every device (Apple/Google/Windows emoji fonts differ), work offline, and need no CDN.
/* eslint-disable */
export const TWEMOJI_AVATARS: Record<string, string> = ${JSON.stringify(map, null, 2)}
`
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'react', 'twemojiAvatars.ts')
writeFileSync(dest, out)
const total = Object.values(map).reduce((n, s) => n + s.length, 0)
console.error(`\nwrote ${dest} — ${EMOJI.length} emoji, ${(total / 1024).toFixed(1)} KiB of SVG`)
